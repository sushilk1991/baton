#!/bin/sh
# Emit real CLI defaults without reading or writing the user's configuration.
set -eu

binary=${1:-"$PWD/bin/baton"}
case "$binary" in
  /*) ;;
  *) echo "usage: $0 /absolute/path/to/baton" >&2; exit 2 ;;
esac

# config show is read-only. A fresh HOME and empty environment exclude all
# user XDG overrides; only this owned scratch file needs removal afterward.
scratch=$(mktemp -d)
trap 'rm -f "$scratch/defaults.toml"; rmdir "$scratch"' 0
env -i PATH="$PATH" LC_ALL=C HOME="$scratch" USERPROFILE="$scratch" \
  XDG_CONFIG_HOME="$scratch/config" XDG_STATE_HOME="$scratch/state" \
  XDG_CACHE_HOME="$scratch/cache" XDG_DATA_HOME="$scratch/data" \
  "$binary" config show > "$scratch/defaults.toml"

# Keep every policy value from the binary. The cache path alone is omitted
# because a copied temporary path would override the reader's XDG default.
cat <<'HEADER'
# Generated by scripts/config-reference.sh from baton config show.
# Slot counts reflect the generation host; see configuration.md for formulas.
# Omit cache.dir to use your own XDG cache directory.
HEADER
sed 's@^  dir = .*@  # dir defaults to XDG_CACHE_HOME/baton (or ~/.cache/baton).@' \
  "$scratch/defaults.toml"
